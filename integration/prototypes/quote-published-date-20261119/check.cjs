const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { load, createStore, initialState } = require('../web-quotations/isolation.cjs');
const { patchBuyerQuoteDate } = require('./patch.cjs');
const baseline = fs.readFileSync(process.env.BUYER_BASELINE || path.resolve(__dirname,'../../../buyer-room.html'), 'utf8');
test('published date comes from immutable CMS receipt, with no new writes or changed version cache key', async () => {
  const state = initialState();
  const wixData = createStore(state, () => {});
  const ready = load('backend/webQuotationCustomer.js', ['isWebQuotationCustomer', 'isWebQuotationReady']);
  const projection = load('backend/masterQuoteProjection.js', ['createMasterQuoteProjection','presentMasterQuote'], { createHash, ...ready });
  const data = load('backend/masterWebQuotationData.js', ['applyWebQuotations'], { wixData, ...projection, ...ready });
  const customer = {customerId:'QA-A',preferredCurrency:'USD',quotationMode:'WEB',webQuotationStatus:'READY',accessStatus:'ACTIVE'};
  const selection = {id:'S',customerId:'QA-A',barcode:'2000000000015',ea:12,catalogueEa:12};
  const receipt = {_id:'Q',customerId:'QA-A',selectionId:'S',barcode:selection.barcode,version:3,enabled:true,currency:'USD',priceEa:2,priceCtn:24,_createdDate:'2026-11-19T03:01:02.000Z'};
  await wixData.insert('MasterWebQuotePublications',receipt);
  const snapshot = JSON.stringify(wixData.rows('MasterWebQuotePublications'));
  const first = (await data.applyWebQuotations(customer,[selection]))[0];
  const second = (await data.applyWebQuotations(customer,[selection]))[0];
  assert.equal(first.quoteEffectiveAt,'WEB-3');
  assert.equal(first.quotePublishedAt,receipt._createdDate);
  assert.equal(second.quotePublishedAt,first.quotePublishedAt);
  assert.equal(first.vipPriceCtn,24);
  assert.equal(JSON.stringify(wixData.rows('MasterWebQuotePublications')),snapshot);
  await wixData.update('MasterWebQuotePublications',{...receipt,_createdDate:'WEB-3'});
  assert.equal((await data.applyWebQuotations(customer,[selection]))[0].quotePublishedAt,'');
  assert.equal((await data.applyWebQuotations(customer,[{...selection,removed:true}]))[0].quoteActive,false);
});
test('Buyer renders actual local publication time and never turns WEB versions into 2001 dates', () => {
  const html = patchBuyerQuoteDate(baseline);
  const code = html.slice(html.indexOf('function row(item,'),html.indexOf('\n\nfunction isAwaiting'));
  const format = html.slice(html.indexOf('function compactTime('), html.indexOf('\nfunction imageUrl'));
  const context = {state:{pendingRemovals:new Map(),pendingRestores:new Map()},esc:String,num:Number,thumbnail:()=>'',priceCell:()=>'',compactTime:v=>v,Date,Intl};
  vm.createContext(context); vm.runInContext(format+'\n'+code,context);
  const item = {id:'S',quoteActive:true,quoteEffectiveAt:'WEB-3',quotePublishedAt:'2026-11-19T03:01:02.000Z'};
  const rendered = context.row(item);
  assert(!rendered.includes('01-03-01'));
  assert(!context.row({...item,quotePublishedAt:''}).includes('01-03-01'));
  assert(context.row({...item,quoteActive:false}).includes('Waiting'));
  assert(rendered.includes(context.compactTime(item.quotePublishedAt)));
});
